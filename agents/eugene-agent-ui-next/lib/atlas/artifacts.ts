/** Word (.docx) document generated from the markdown body. */
export async function toDocxBuffer(a: Artifact): Promise<Buffer> {
  const children: Paragraph[] = [
    new Paragraph({ heading: HeadingLevel.TITLE, children: [new TextRun({ text: a.title })] }),
    new Paragraph({
      children: [new TextRun({ text: `CSL Atlas · ${new Date(a.created_at).toISOString().slice(0, 10)}`, italics: true, color: "718096" })],
    }),
    new Paragraph({ text: "" }),
    ...markdownToParagraphs(a.body_md),
  ];
  const doc = new Document({ sections: [{ children }] });
  return Packer.toBuffer(doc);
}

/** Pragmatic Markdown → docx paragraphs (headings, lists, bold, code). */
function markdownToParagraphs(md: string): Paragraph[] {
  const out: Paragraph[] = [];
  for (const rawLine of md.replace(/\r/g, "").split("\n")) {
    const line = rawLine.replace(/\s+$/, "");
    if (!line.trim()) {
      out.push(new Paragraph({ text: "" }));
      continue;
    }
    const h = line.match(/^(#{1,3})\s+(.*)$/);
    if (h) {
      const level = h[1].length;
      out.push(
        new Paragraph({
          heading:
            level === 1 ? HeadingLevel.HEADING_1 : level === 2 ? HeadingLevel.HEADING_2 : HeadingLevel.HEADING_3,
          children: inlineRuns(h[2]),
        })
      );
      continue;
    }
    const bullet = line.match(/^\s*[-*+]\s+(.*)$/);
    if (bullet) {
      out.push(new Paragraph({ bullet: { level: 0 }, children: inlineRuns(bullet[1]) }));
      continue;
    }
    const numbered = line.match(/^\s*\d+\.\s+(.*)$/);
    if (numbered) {
      out.push(new Paragraph({ numbering: { reference: "num", level: 0 }, children: inlineRuns(numbered[1]) }));
      continue;
    }
    out.push(new Paragraph({ children: inlineRuns(line) }));
  }
  return out;
}

/** Parse **bold** and `code` inline spans into docx TextRuns. */
function inlineRuns(text: string): TextRun[] {
  const runs: TextRun[] = [];
  const re = /(\*\*([^*]+)\*\*|`([^`]+)`)/g;
  let last = 0;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text)) !== null) {
    if (m.index > last) runs.push(new TextRun({ text: text.slice(last, m.index) }));
    if (m[2] != null) runs.push(new TextRun({ text: m[2], bold: true }));
    else if (m[3] != null) runs.push(new TextRun({ text: m[3], font: "Consolas" }));
    last = m.index + m[0].length;
  }
  if (last < text.length) runs.push(new TextRun({ text: text.slice(last) }));
  return runs.length ? runs : [new TextRun({ text })];
}

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}
