import "server-only";
import { marked } from "marked";
import {
  Document,
  Packer,
  Paragraph,
  TextRun,
  HeadingLevel,
} from "docx";
import { query } from "./db";

/**
 * Published artifacts — a saved, shareable snapshot of an answer.
 *
 * Mirrors Claude's "Publish": the owner turns an answer into a stable page at
 * /nextgen/a/<id> that anyone who can reach the app can view and download as
 * Markdown, HTML, Word (.docx) or PDF (browser print of the page). Everything
 * is generated on-box with pure-JS libraries — no cloud calls, so it works in
 * the no-egress VPC.
 */

export interface Artifact {
  id: string;
  user_id: string;
  conversation_id: string | null;
  title: string;
  body_md: string;
  source: string | null;
  revoked: boolean;
  created_at: string;
}

export async function createArtifact(
  userId: string,
  input: { title: string; bodyMd: string; source?: string | null; conversationId?: string | null }
): Promise<Artifact> {
  const rows = await query<Artifact>(
    `INSERT INTO artifacts (user_id, conversation_id, title, body_md, source)
     VALUES ($1, $2, $3, $4, $5)
     RETURNING *`,
    [
      userId,
      input.conversationId ?? null,
      (input.title || "Untitled").slice(0, 200),
      input.bodyMd ?? "",
      input.source ?? null,
    ]
  );
  return rows[0];
}

/** Public fetch (by id) — returns null when missing or revoked. */
export async function getArtifact(id: string): Promise<Artifact | null> {
  const rows = await query<Artifact>(
    "SELECT * FROM artifacts WHERE id = $1 AND revoked = false",
    [id]
  );
  return rows[0] ?? null;
}

export async function listArtifacts(userId: string): Promise<Artifact[]> {
  return query<Artifact>(
    "SELECT * FROM artifacts WHERE user_id = $1 AND revoked = false ORDER BY created_at DESC LIMIT 100",
    [userId]
  );
}

export async function revokeArtifact(id: string, userId: string): Promise<boolean> {
  const rows = await query<{ id: string }>(
    "UPDATE artifacts SET revoked = true WHERE id = $1 AND user_id = $2 RETURNING id",
    [id, userId]
  );
  return rows.length > 0;
}

