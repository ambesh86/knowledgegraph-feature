#!/usr/bin/env python3
"""
Dump every node + relationship from the AWS Eugene Neo4j into a single .cypher
file that can be replayed into the local Neo4j with `cypher-shell`.

USAGE
-----
    # 1. Be on the VPN that routes 10.88.*
    # 2. Install the driver in any Python on PATH:
    #        pip3 install --user neo4j
    # 3. Run:
    NEO4J_URI=neo4j+ssc://10.88.203.251:7687 \
    NEO4J_USERNAME=neo4j \
    NEO4J_PASSWORD=<aws-prod-password> \
    BATCH=1000 \
    python3 bin/dump_aws_neo4j_to_cypher.py > dumps/eugene_aws.cypher

    # 4. Import into your LOCAL Neo4j:
    docker exec -i eugene-neo4j cypher-shell -u neo4j -p eugene_local_2024 \
      --database neo4j --format plain --fail-fast < dumps/eugene_aws.cypher

    # Or to wipe local first:
    docker exec -i eugene-neo4j cypher-shell -u neo4j -p eugene_local_2024 \
      'MATCH (n) DETACH DELETE n;'

NOTES
-----
- Uses MERGE on node_id (assumes every node has a unique node_id property —
  which is the convention in the Eugene KG). Re-running the import is therefore
  idempotent.
- Uses APOC-free pure Cypher; no APOC required at either end.
- For multi-million-node graphs prefer the neo4j-admin dump/load path
  (much faster). For Eugene's KG (~k-scale), this script is fine and finishes
  in seconds-to-minutes.
"""

from __future__ import annotations

import json
import os
import sys

from neo4j import GraphDatabase


# -----------------------------------------------------------------------------
# helpers
# -----------------------------------------------------------------------------

def cypher_literal(value):
    """Convert a Python value into a Cypher literal for inlining into MERGE/SET."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list):
        return "[" + ", ".join(cypher_literal(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"`{k}`: {cypher_literal(v)}" for k, v in value.items()) + "}"
    # Strings: use double-quoted with JSON escaping so embedded quotes/newlines are safe.
    return json.dumps(str(value), ensure_ascii=False)


def props_to_cypher(props: dict, indent: str = "  ") -> str:
    if not props:
        return ""
    return ",\n".join(f"{indent}`{k}`: {cypher_literal(v)}" for k, v in props.items())


def emit_node(stream, labels, props):
    """One MERGE per node, keyed on node_id (falls back to a synthetic id)."""
    node_id = props.get("node_id") or props.get("id")
    if not node_id:
        # Skip orphan nodes that have no stable identifier — they cannot be
        # safely MERGE-keyed and would be duplicated on re-runs.
        return False
    label_part = ":".join(f"`{lbl}`" for lbl in labels) if labels else "Node"
    body = props_to_cypher(props)
    stream.write(
        f"MERGE (n:{label_part} {{node_id: {cypher_literal(node_id)}}})\n"
        + (f"  SET n += {{\n{body}\n  }};\n" if body else "  ;\n")
    )
    return True


def emit_rel(stream, src_id, dst_id, rel_type, props):
    body = props_to_cypher(props)
    rel_type = rel_type or "RELATED"
    # Sanitise rel type to a safe Cypher identifier
    safe = "".join(c if c.isalnum() else "_" for c in rel_type) or "RELATED"
    stream.write(
        "MATCH (a {{node_id: {src}}}), (b {{node_id: {dst}}})\n".format(
            src=cypher_literal(src_id), dst=cypher_literal(dst_id)
        )
        + f"MERGE (a)-[r:`{safe}`]->(b)\n"
        + (f"  SET r += {{\n{body}\n  }};\n" if body else "  ;\n")
    )


# -----------------------------------------------------------------------------
# main
# -----------------------------------------------------------------------------

def main() -> int:
    uri = os.environ.get("NEO4J_URI") or "neo4j+ssc://10.88.203.251:7687"
    user = os.environ.get("NEO4J_USERNAME") or "neo4j"
    password = os.environ.get("NEO4J_PASSWORD")
    if not password:
        sys.stderr.write("ERROR: set NEO4J_PASSWORD\n")
        return 2
    batch = int(os.environ.get("BATCH", "1000"))
    database = os.environ.get("NEO4J_DATABASE") or None

    out = sys.stdout  # the cypher file is the stdout, logs go to stderr
    log = sys.stderr.write

    log(f"connecting to {uri} as {user}\n")
    driver = GraphDatabase.driver(uri, auth=(user, password))

    out.write("// Eugene AWS Neo4j dump — generated by dump_aws_neo4j_to_cypher.py\n")
    out.write("// Idempotent: every node/edge uses MERGE keyed on node_id.\n\n")

    with driver.session(database=database) as sess:
        # Pass 1 — nodes
        # The skip/limit pagination keeps the working set bounded for big graphs.
        offset = 0
        emitted = 0
        skipped = 0
        while True:
            recs = list(sess.run(
                "MATCH (n) RETURN labels(n) AS labels, properties(n) AS props "
                "ORDER BY id(n) SKIP $off LIMIT $lim",
                off=offset, lim=batch,
            ))
            if not recs:
                break
            for r in recs:
                if emit_node(out, r["labels"], r["props"]):
                    emitted += 1
                else:
                    skipped += 1
            offset += len(recs)
            log(f"  nodes processed: {offset} (emitted={emitted}, skipped={skipped})\n")

        log(f"DONE nodes: emitted={emitted}, skipped={skipped} (no node_id)\n")

        # Pass 2 — relationships
        offset = 0
        emitted_r = 0
        skipped_r = 0
        while True:
            recs = list(sess.run(
                "MATCH (a)-[r]->(b) "
                "RETURN a.node_id AS src_id, b.node_id AS dst_id, "
                "       type(r) AS rt, properties(r) AS props "
                "ORDER BY id(r) SKIP $off LIMIT $lim",
                off=offset, lim=batch,
            ))
            if not recs:
                break
            for r in recs:
                if r["src_id"] is None or r["dst_id"] is None:
                    skipped_r += 1
                    continue
                emit_rel(out, r["src_id"], r["dst_id"], r["rt"], r["props"])
                emitted_r += 1
            offset += len(recs)
            log(f"  rels processed: {offset} (emitted={emitted_r}, skipped={skipped_r})\n")
        log(f"DONE rels: emitted={emitted_r}, skipped={skipped_r}\n")

    driver.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
